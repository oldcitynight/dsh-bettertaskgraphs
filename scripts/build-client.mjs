import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const { name: packageName, version, license, repository } = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'))
const sourceUrl = repository.url.replace(/^git\+/, '').replace(/\.git$/, '')
const sources = ['remote.mjs', 'view-model.mjs', 'client.source.mjs'].map(name => {
  const source = readFileSync(new URL(name, root), 'utf8')
  if (/^import\s/m.test(source)) throw new Error(`${name} must be self-contained for the DSH lazy client factory`)
  return source.replace(/^export\s+(?=(?:function|const|class)\b)/gm, '')
})
const output = `// SPDX-License-Identifier: ${license}
// Corresponding source: ${sourceUrl}/tree/v${version}
// Generated by scripts/build-client.mjs.
window.__ModuleLoader__.load({id:${JSON.stringify(packageName)},factory(require){
${sources.join('\n')}
return createClientPlugin(require('react'),require('zod').z,createRemoteContribution,graphPresentation,branchLayout);
}});
`
if (process.argv.slice(2).join(' ') === '--check') {
  if (readFileSync(new URL('client.js', root), 'utf8') !== output) throw new Error('Transaction graph client bundle is stale')
} else if (process.argv.length === 2) {
  writeFileSync(new URL('client.js', root), output)
} else {
  throw new Error('Use no arguments to build, or --check to verify')
}
